#!/usr/bin/env node
/**
 * Builds the service icons from src/*.js:
 *   <name>.html        one self-contained Hairline page per figure, as the hairline-create skill assembles it
 *   service-icons.js   one classic script for embedding without an iframe: kernel + figures + src/embed.js
 *
 * Usage: node build-icons.mjs
 * The Hairline kernel is read from the installed skill; set HAIRLINE_SKILL to its folder if it is not in ~/.claude/skills.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const NAMES = ["diagnostics", "gums", "implant", "prosthetics", "tmj", "smile", "braces"];
const here = dirname(fileURLToPath(import.meta.url));
const skill = process.env.HAIRLINE_SKILL || join(homedir(), ".claude", "skills", "hairline-create");
const { assemble } = await import(pathToFileURL(join(skill, "build.mjs")).href);
const text = (file) => readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim();

const kernel = text(join(skill, "kernel.js"));
const sources = NAMES.map((name) => ({ name, code: text(join(here, "src", `${name}.js`)) }));

for (const { name, code } of sources) writeFileSync(join(here, `${name}.html`), assemble(code));

const indent = (code) => code.split("\n").map((line) => (line ? "  " + line : line)).join("\n");
const bundle = [
  "/* Service icons for the Dominanta site. Generated by build-icons.mjs from src/: edit the sources, not this file. */",
  "(function () {",
  '"use strict";',
  kernel,
  "var figures = {};",
  "function hairline(figure) { figures[figure.name] = figure; }",
  ...sources.map(({ name, code }) => `/* ---- ${name} ---- */\n(function () {\n${indent(code)}\n})();`),
  text(join(here, "src", "embed.js")),
  "})();",
  "",
].join("\n");
writeFileSync(join(here, "service-icons.js"), bundle);
console.log(`built ${NAMES.length} pages and service-icons.js (${Math.round(bundle.length / 1024)} KB)`);
